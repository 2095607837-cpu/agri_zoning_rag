def _flat(lst):
    """Flatten nested lists recursively."""
    result = []
    for item in (lst or []):
        if isinstance(item, list):
            result.extend(_flat(item))
        else:
            result.append(item)
    return result

def make_q(cap, fid, qtype, diff, question, answer, gold_doc_ids, gold_sections, gold_chunks,
           must_retrieve, optional_retrieve=None, negative_sections=None,
           must_include=None, must_not_include=None, citations=None,
           features=None, eno=None, rewrite_type=None, ood_type=None,
           expected_chunk_num=None, expected_context_expand=None, difficulty_score=None,
           extra=None):
    """Build a complete question dict."""
    n = next(ctr)
    qid = fid
    base = {
        "id": qid, "question": question, "answer": answer,
        "capability": cap, "query_type": qtype,
        "difficulty": diff,
        "gold_doc_ids": gold_doc_ids, "gold_sections": gold_sections, "gold_chunks": gold_chunks,
        "retrieval_eval": {
            "must_retrieve": _flat(must_retrieve),
            "optional_retrieve": _flat(optional_retrieve),
            "negative_sections": _flat(negative_sections)
        },
        "generator_eval": {
            "must_include": must_include or [],
            "must_not_include": must_not_include or []
        },
        "expected_citation": citations or [],
        "keywords": []
    }
    # Compute difficulty_score from features
    score = 0
    if len(gold_sections) == 1: score += 1
    elif len(gold_sections) >= 2: score += 1
    if len(set(gold_doc_ids)) > 1: score += 2
    feats = features or []
    if "rewrite" in feats or rewrite_type: score += 1
    if "numeric" in feats: score += 1
    if "table" in feats: score += 1
    if "multi_hop" in feats: score += 2
    base["difficulty_score"] = score
    base["difficulty"] = "easy" if score <= 2 else ("medium" if score <= 5 else "hard")
    base["features"] = feats
    if rewrite_type: base["rewrite_type"] = rewrite_type
    if ood_type: base["ood_type"] = ood_type
    ecn = expected_chunk_num or len(gold_chunks)
    ece = expected_context_expand if expected_context_expand is not None else (len(gold_sections) > 1 and len(set(gold_doc_ids)) == 1)
    base["expected_chunk_num"] = ecn
    base["expected_context_expand"] = ece
    base["keywords"] = question.replace("？","").replace("，","").replace("、","").split()[:8]
    if extra: base.update(extra)
    return base


